// Statistikani yangilash funktsiyasi
function updateStats(neighborhoodData) {
    const crimeTypeFilter = document.getElementById('crime-type-filter').value;
    const timeFilter = document.getElementById('time-filter').value;
    
    // Sarlavhani yangilash
    document.querySelector('.neighborhood-title').textContent = neighborhoodData.name;
    
    // Mahalla ma'lumotlarini ko'rsatish
    document.getElementById('neighborhood-info').style.display = 'block';
    document.getElementById('area').textContent = neighborhoodData.area;
    document.getElementById('population').textContent = neighborhoodData.population;
    document.getElementById('safety-level').textContent = neighborhoodData.safetyLevel;
    
    // Statistikani ko'rsatish
    let statsHTML = '';
    let total = 0;
    
    // Filtrlangan ma'lumotlarni olish
    let crimesToShow = {};
    if (timeFilter === 'all') {
        crimesToShow = neighborhoodData.crimes;
    } else {
        crimesToShow = neighborhoodData.trends[timeFilter];
    }
    
    // Jinoyat turlarini ko'rsatish
    Object.entries(crimesToShow).forEach(([crime, count]) => {
        if (crimeTypeFilter === 'all' || crimeTypeFilter === crime) {
            total += count;
            statsHTML += `
                <div class="crime-item">
                    <span class="crime-type">${crime}:</span>
                    <span class="crime-count">${count} ta</span>
                </div>
            `;
        }
    });
    
    statsHTML += `
        <div class="total-stats">
            <span>Jami:</span>
            <span>${total} ta</span>
        </div>
    `;
    
    document.getElementById('crime-stats').innerHTML = statsHTML;
    
    // Grafikni yangilash    
    updateChart(crimesToShow, neighborhoodData.name, crimeTypeFilter);
}

// Grafikni yangilash funktsiyasi
function updateChart(crimeData, neighborhoodName, crimeTypeFilter) {    
    let categories = [];
    let seriesData = [];
    
    if (crimeTypeFilter === 'all') {
        categories = Object.keys(crimeData);
        seriesData = Object.values(crimeData);
    } else {
        categories = [crimeTypeFilter];
        seriesData = [crimeData[crimeTypeFilter]];
    }
    
    chart1.updateOptions({
        series: [{
            name: 'Jinoyatlar soni',
            data: seriesData
        }],
        xaxis: { categories },
        title: {
            text: `${neighborhoodName} mahallasi jinoyat statistikasi`,
            style: {
                fontSize: '16px',
                fontWeight: 'bold'
            }
        }
    });    
}

